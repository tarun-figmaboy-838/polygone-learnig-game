// Pack the generated measuring artwork for runtime playback.
// node tools/build-measuring.js
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');
const root = path.join(__dirname, '..');
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const page = await browser.newPage();
    const source = fs.readFileSync(path.join(root, 'assets/swiftee/swiftee-measuring-draft.png')).toString('base64');
    const result = await page.evaluate(async base64 => {
      const image = new Image(); image.src = 'data:image/png;base64,' + base64; await image.decode();
      const canvas = document.createElement('canvas'); canvas.width = image.width; canvas.height = image.height;
      const ctx = canvas.getContext('2d'); ctx.drawImage(image, 0, 0);
      const pixels = ctx.getImageData(0, 0, canvas.width, canvas.height), data = pixels.data;
      const w = canvas.width, h = canvas.height, size = w * h;
      // Remove only neutral background connected to the outside; enclosed eye
      // highlights and the dark contour remain part of the character.
      const exterior = new Uint8Array(size), queue = new Int32Array(size); let head = 0, tail = 0;
      function visit(i) {
        if (exterior[i]) return;
        const p = i * 4, r = data[p], g = data[p + 1], b = data[p + 2];
        if (Math.max(r, g, b) - Math.min(r, g, b) > 32 || Math.min(r, g, b) < 82) return;
        exterior[i] = 1; queue[tail++] = i;
      }
      for (let x = 0; x < w; x++) { visit(x); visit((h - 1) * w + x); }
      for (let y = 0; y < h; y++) { visit(y * w); visit(y * w + w - 1); }
      while (head < tail) {
        const i = queue[head++], x = i % w;
        if (x) visit(i - 1); if (x < w - 1) visit(i + 1);
        if (i >= w) visit(i - w); if (i < size - w) visit(i + w);
      }
      for (let i = 0; i < size; i++) if (exterior[i]) data[i * 4 + 3] = 0;
      ctx.putImageData(pixels, 0, 0);
      const atlas = document.createElement('canvas'); atlas.width = 1024; atlas.height = 512;
      const out = atlas.getContext('2d'); out.imageSmoothingQuality = 'high';
      const bounds = [];
      for (let frame = 0; frame < 8; frame++) {
        const x0 = Math.round((frame % 4) * w / 4), x1 = Math.round((frame % 4 + 1) * w / 4);
        const y0 = Math.round(Math.floor(frame / 4) * h / 2), y1 = Math.round((Math.floor(frame / 4) + 1) * h / 2);
        let left = x1, right = x0, top = y1, bottom = y0;
        for (let y = y0; y < y1; y++) for (let x = x0; x < x1; x++) {
          if (data[(y * w + x) * 4 + 3]) { left = Math.min(left, x); right = Math.max(right, x); top = Math.min(top, y); bottom = Math.max(bottom, y); }
        }
        const sw = right - left + 1, sh = bottom - top + 1;
        const scale = Math.min(216 / sw, 204 / sh), dw = sw * scale, dh = sh * scale;
        const dx = (frame % 4) * 256 + (256 - dw) / 2, dy = Math.floor(frame / 4) * 256 + 230 - dh;
        out.drawImage(canvas, left, top, sw, sh, dx, dy, dw, dh);
        bounds.push({ x: +(dx % 256).toFixed(2), y: +(dy % 256).toFixed(2), width: +dw.toFixed(2), height: +dh.toFixed(2) });
      }
      return { png: atlas.toDataURL('image/png').split(',')[1], bounds };
    }, source);
    fs.writeFileSync(path.join(root, 'assets/swiftee/swiftee-measuring.png'), Buffer.from(result.png, 'base64'));
    const spec = { image: 'assets/swiftee/swiftee-measuring.png', cell: 256, cols: 4, rows: 2, frames: 8, baseline: 230,
      fps: 14, order: [0, 1, 2, 3, 4, 5, 6, 7, 6, 5, 4, 3, 2, 1], bounds: result.bounds };
    fs.writeFileSync(path.join(root, 'assets/swiftee/swiftee-measuring.json'), JSON.stringify(spec, null, 2) + '\n');
    fs.writeFileSync(path.join(root, 'src/character/measuring-frames.js'), '// Generated by tools/build-measuring.js\n(function(g){g.MeasuringFrames=' + JSON.stringify(spec) + ';})(typeof window!=="undefined"?window:globalThis);\n');
    console.log('Packed 8 transparent, baseline-aligned frames into assets/swiftee/swiftee-measuring.png');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
